def validate_release_registration():
    records = known_sources()
    require(set(REVIEWED_RELEASE_ASSETS) == set(records),
            'Release assets and anonymous download readbacks are not registered for all40')
    asset_ids = set()
    for motion, item in REVIEWED_RELEASE_ASSETS.items():
        require(set(item) == {'asset_id', 'asset_name', 'url', 'bytes', 'sha256',
                             'anonymous_download_verified', 'verification_sha256'},
                'Unreviewed release registration fields')
        source = records[motion]
        validate_asset_location(motion, item['url'], item['asset_name'])
        numeric_id = type(item['asset_id']) is int and item['asset_id'] > 0 and item['asset_id'] not in asset_ids
        observed_unknown_id = item['asset_id'] is None and item['verification_sha256'] == RANGE_READBACK_SHA256
        require((numeric_id or observed_unknown_id) and
                type(item['bytes']) is int and item['bytes'] == source['bytes'] and item['sha256'] == source['sha256'] and
                item['anonymous_download_verified'] is True and HASH.fullmatch(item['verification_sha256']),
                'Release identity or actual download verification differs')
        if numeric_id:
            asset_ids.add(item['asset_id'])


def reject_private_text(value):
    if type(value) is dict:
        for key, child in value.items():
            reject_private_text(key)
            reject_private_text(child)
    elif type(value) is list:
        for child in value:
            reject_private_text(child)
    elif type(value) is str:
        require(not re.search(r'\blocalhost\b', value, re.I), 'Local host in public media text')
        for match in IP_LITERAL.finditer(value):
            try:
                address = ipaddress.ip_address(match.group())
            except ValueError:
                continue
            require(not (address.is_private or address.is_loopback), 'Private IP in public media text')


def validate_public_media(media, data):
    """Validate values, original source identities and actual hosting proof; never score."""
    if exact(media, LEGACY_EMPTY):
        return
    records = known_sources()
    require(type(media) is dict and set(media) == TOP_FIELDS and media['schema'] == MEDIA_SCHEMA and
            media['expected_common_motions'] == 40 and type(media['expected_common_motions']) is int and
            media['status'] in ('published40', 'download_only40') and media['render_revision'] == RENDER_REVISION and
            exact(media['authorization'], AUTHORIZATION), 'Public media top-level contract differs')
    require(type(media['credits']) is str and 0 < len(media['credits'].strip()) <= 8000,
            'Media credits are missing')
    require(type(media['items']) is list and len(media['items']) == 40, 'Exactly40 accepted media items required')
    reject_private_text(media)
    rows = [r for r in data['results'] if r.get('scope') == 'per_motion' and r.get('dataset') == 'lafan40' and
            r.get('condition') == 'nominal' and r.get('mode') == 'native_position' and type(r.get('seed')) is int and r['seed'] == 0]
    by_id = {r['id']: r for r in rows}
    require(len(rows) == len(by_id) == 80 and {r['motion_id'] for r in rows} == set(records),
            'Media does not match unchanged effective Common40 selection')
    validate_release_registration()
    publication = 'published' if media['status'] == 'published40' else 'download_only'
    seen = set()
    selected_conditions = {'nominal': 0, 'aligned_nominal': 0}
    if publication == 'published':
        require(set(REVIEWED_PLAYBACK) == set(records), 'Actual desktop/mobile/seek proof is not registered for all40')
    for item in media['items']:
        require(type(item) is dict and set(item) == ITEM_FIELDS, 'Public media item fields differ')
        motion = item['motion_id']
        require(motion in records and motion not in seen, 'Unknown or duplicate media motion')
        seen.add(motion); source = records[motion]; asset = REVIEWED_RELEASE_ASSETS[motion]
        for field in ('sha256', 'bytes', 'duration_s', 'width', 'height', 'fps', 'poster_bytes',
                      'poster_sha256', 'source_result_ids', 'source_selected_conditions'):
            require(exact(item[field], source[field]), 'Accepted media field differs: ' + field)
        require(item['public_release_approved'] is True and item['is_new_render'] is True and item['full_episode'] is True
                and item['source_recorded_trajectory_reused'] is True and item['new_physical_retest'] is False
                and item['legacy_fail_label_is_current_completion'] is False and item['render_revision'] == RENDER_REVISION
                and item['publication_status'] == publication,
                'Media approval, preserved trajectory or publication state differs')
        require(item['poster'] == './' + poster_path(motion), 'Unreviewed poster filename')
        for field in ('asset_id', 'asset_name', 'url'):
            require(exact(item[field], asset[field]), 'Actual release asset differs: ' + field)
        for field in ('label', 'description', 'credits', 'restrictions'):
            require(type(item[field]) is str and 0 < len(item[field].strip()) <= 8000,
                    'Missing media display text: ' + field)
        require(len(item['source_result_ids']) == 2 and len(set(item['source_result_ids'])) == 2,
                'Two original source result IDs required')
        for robot, rid in zip(('rp1', 'g1'), item['source_result_ids']):
            row = by_id.get(rid)
            require(row is not None and row['robot'] == robot and row['motion_id'] == motion and
                    row['fullwindow']['run_id'] == source['source_scientific_run_ids'][robot],
                    'Original source result/run identity differs')
            selected_conditions[source['source_selected_conditions'][robot]] += 1
        proof = item['playback_verification']
        require(type(proof) is dict and set(proof) == PLAYBACK_FIELDS and
                proof['url'] == item['url'] and proof['sha256'] == item['sha256'], 'Playback identity differs')
        expected = {'status': 'passed' if publication == 'published' else 'not_verified',
                    'url': item['url'], 'sha256': item['sha256'],
                    'desktop': publication == 'published', 'mobile': publication == 'published',
                    'seek': publication == 'published'}
        require(exact(proof, expected), 'Playback status cannot be inferred from a download')
        if publication == 'published':
            actual = REVIEWED_PLAYBACK[motion]
            require(set(actual) == {'proof', 'verification_sha256'} and exact(actual['proof'], proof) and
                    HASH.fullmatch(actual['verification_sha256']), 'Playback proof differs from actual receipt')
    require(seen == set(records) and selected_conditions == {'nominal': 70, 'aligned_nominal': 10},
            'Original recorded source-condition coverage differs')


def jpeg_dimensions(raw):
    require(raw.startswith(b'\xff\xd8') and raw.endswith(b'\xff\xd9'), 'Accepted poster must remain a JPEG')
    offset = 2
    while offset < len(raw) - 1:
        require(raw[offset] == 0xff, 'Invalid JPEG marker')
        while offset < len(raw) and raw[offset] == 0xff:
            offset += 1
        require(offset < len(raw), 'Incomplete JPEG marker')
        marker = raw[offset]; offset += 1
        if marker in {0x01, *range(0xd0, 0xda)}:
            continue
        require(offset + 2 <= len(raw), 'Incomplete JPEG segment')
        size = int.from_bytes(raw[offset:offset+2], 'big')
        require(size >= 2 and offset + size <= len(raw), 'Invalid JPEG segment size')
        if marker in {0xc0, 0xc1, 0xc2, 0xc3, 0xc5, 0xc6, 0xc7, 0xc9, 0xca, 0xcb, 0xcd, 0xce, 0xcf}:
            require(size >= 8, 'Incomplete JPEG frame header')
            return (int.from_bytes(raw[offset+5:offset+7], 'big'), int.from_bytes(raw[offset+3:offset+5], 'big'))
        require(marker != 0xda, 'JPEG frame header missing before scan')
        offset += size
    raise ValueError('JPEG dimensions missing')


@dataclass(frozen=True)
class MediaReview:
    media: dict
    media_sha256: str
    media_state: dict
    additional_files: frozenset
    binary_files: dict


def verify_binary_file(root, name, review):
    require(name in review.binary_files, 'Unregistered public binary file')
    expected = review.binary_files[name]
    raw = read_ordinary(root, name, 2 * 1024**2)
    require(len(raw) == expected['bytes'] and sha(raw) == expected['sha256'] and
            jpeg_dimensions(raw) == (1920, 1080), 'Accepted poster bytes, hash or dimensions changed')


def assert_media_unchanged(root, review):
    require(sha(read_ordinary(root, 'media.json')) == review.media_sha256, 'Media changed after validation')


def prepare_media(root, data):
    raw = read_ordinary(root, 'media.json')
    media = parse_json(raw)
    validate_public_media(media, data)
    digest = sha(raw)
    if exact(media, LEGACY_EMPTY):
        require(digest == LEGACY_EMPTY_SHA256, 'Legacy empty media bytes changed')
        return MediaReview(media, digest, dict(LEGACY_MEDIA_STATE), frozenset({MEDIA_SCRIPT}), {})
    for name, (size, digest_expected) in SCIENTIFIC_FILES.items():
        content = read_ordinary(root, name)
        require(len(content) == size and sha(content) == digest_expected, 'Media publication changed science/hardware bytes')
    require(exact(parse_json(read_ordinary(root, 'data.json')), data), 'Media identity input differs from public data')
    binaries = {poster_path(m): {'bytes': r['poster_bytes'], 'sha256': r['poster_sha256']}
                for m, r in known_sources().items()}
    review = MediaReview(media, digest,
        {'public_new_common40': 40, 'public_new_extreme5': 0, 'source_media_sha256': digest},
        frozenset(additional_public_files(media['status'])), binaries)
    for name in binaries:
        verify_binary_file(root, name, review)
    return review


